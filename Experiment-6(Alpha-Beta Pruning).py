import math
#Alpha-beta purning function
def alpha_beta(depth, nodeIndex, maximizingplayer,values, alpha, beta, height):
  if depth == height:
    return values[nodeIndex]

  if maximizingplayer:
    best = -math.inf

    for i in range(2):
      value = alpha_beta(
          depth + 1,
          nodeIndex * 2 + i,
          False, # Corrected: false -> False
          values,
          alpha,
          beta,
          height
      )

      best = max(best, value) # Corrected: best - max -> best = max
      alpha = max(alpha, best)

      if beta <= alpha:
        break

    return best

  else:
    best = math.inf

    for i in range(2):
      value = alpha_beta(
          depth + 1,
          nodeIndex * 2 + i,
          True, # Corrected: true -> True
          values,
          alpha,
          beta,
          height
      )
      best = min(best, value)
      beta = min(beta, best)

      #alpha cut-off
      if beta <= alpha:
         break
  return best

#main program
values = list(map(int, input("Enter 8 leaf node values: ") .split())) # Corrected: indentation
height = 3
result = alpha_beta(
  0,
  0,
  True, # Corrected: true -> True
  values, # Corrected: missing values list
  -math.inf, # Corrected: -math,inf -> -math.inf and correct position
  math.inf, # Corrected: correct position
  height
)
print("\noptimal value:", result)