def objective(x):
    return -(x - 3) ** 2 + 9

def hill_climbing(start):
    current = start

    while True:
        neighbours = [current - 1, current + 1]
        best = current

        for n in neighbours:
            if objective(n) > objective(best):
                best = n

        if best == current:
            break

        current = best

    return current

start = 0
optimal = hill_climbing(start)

print("Starting State:", start)
print("Optimal State:", optimal)
print("Maximum Value:", objective(optimal))